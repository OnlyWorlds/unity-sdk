#!/usr/bin/env python3
"""Generate the SDK's slug table from Unicode's UnicodeData.txt, at the version the NFC tables pin.

The folder format's section 3.2 makes a new element's slug so: the name in NFKD; U+0300 to U+036F dropped and no
other mark; lowercased; every run outside a-z and 0-9 one hyphen; hyphens at both ends dropped; cut at 40 and the new
end's hyphens dropped. `string.Normalize(FormKD)` is the runtime's own tables, and Mono's leaves a ligature and the
mathematical letters whole, so `OWFolderWriter.Slugify` reads this table instead.

What a code point gives a slug depends on that code point alone (NFKD's reordering moves only marks of a non-zero
class, and never across a letter or a digit, which are all class 0): its full compatibility decomposition, each part
lowercased (UnicodeData field 13), kept when it is a to z or 0 to 9, dropped when it is U+0300 to U+036F, and a break
otherwise. The table lists only the code points whose contribution differs from the plain rule (an ASCII letter
lowercased, an ASCII digit kept, U+0300 to U+036F dropped, anything else a break); a contribution is written with `-`
for a break, runs of breaks as one. Hangul syllables decompose to jamo, which give a break, as the plain rule does.

Every code point is also checked against Python's own NFKD when Python's Unicode is the same version, so the
derivation here is checked against an independent one.

Usage:
    python tools/gen_slug.py --dir codegen/schema-dist/fixtures/owworld           # rewrite
    python tools/gen_slug.py --dir codegen/schema-dist/fixtures/owworld --check   # diff only
"""
import argparse
import hashlib
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_nfc import UNICODE_DATA, UNICODE_DATA_SHA256, VERSION, read_pinned  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "Packages", "com.onlyworlds.sdk", "Runtime", "Core", "OWSlugData.cs")


def parse(text):
    """Field 5 (every decomposition, a `<tag>` one included) and field 13 (simple lowercase), by code point."""
    maps, lower = {}, {}
    for line in text.splitlines():
        if not line:
            continue
        f = line.split(";")
        cp = int(f[0], 16)
        if f[1].endswith(", First>") or f[1].endswith(", Last>"):
            if f[5] or f[13]:
                sys.exit("the range at U+%04X carries a mapping" % cp)
            continue
        if f[5]:
            maps[cp] = [int(h, 16) for h in f[5].split() if not h.startswith("<")]
        if f[13]:
            lower[cp] = int(f[13], 16)
    return maps, lower


def full(cp, maps):
    if cp not in maps:
        return [cp]
    out = []
    for part in maps[cp]:
        out.extend(full(part, maps))
    return out


def piece(cp, lower):
    c = lower.get(cp, cp)
    if 0x300 <= cp <= 0x36F:
        return ""
    if 0x61 <= c <= 0x7A or 0x30 <= c <= 0x39:
        return chr(c)
    return "-"


def contribution(cp, maps, lower):
    return re.sub("-+", "-", "".join(piece(p, lower) for p in full(cp, maps)))


def plain(cp):
    if 0x300 <= cp <= 0x36F:
        return ""
    if 0x41 <= cp <= 0x5A:
        return chr(cp + 32)
    if 0x61 <= cp <= 0x7A or 0x30 <= cp <= 0x39:
        return chr(cp)
    return "-"


def python_contribution(cp):
    s = unicodedata.normalize("NFKD", chr(cp))
    s = "".join(c for c in s if not 0x300 <= ord(c) <= 0x36F).lower()
    return re.sub("[^a-z0-9]+", "-", s, flags=re.ASCII)


def render(table):
    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen_slug.py from Unicode %s %s (sha256 %s)." % (VERSION, UNICODE_DATA, UNICODE_DATA_SHA256),
        "// Do not edit by hand: run `python tools/gen_slug.py --dir ...`.",
        "// </auto-generated>",
        "",
        "namespace OnlyWorlds.Sdk",
        "{",
        "    /// <summary>",
        "    /// What a code point gives a new element's slug (folder format section 3.2) where that differs from the plain",
        "    /// rule (an ASCII letter lowercased, an ASCII digit kept, U+0300 to U+036F dropped, anything else a break): its",
        "    /// compatibility decomposition's letters and digits, <c>-</c> for a break.",
        "    /// </summary>",
        "    internal static class OWSlugData",
        "    {",
        "        /// <summary>The Unicode version the table was generated from.</summary>",
        "        internal const string UnicodeVersion = \"%s\";" % VERSION,
        "",
        "        /// <summary>The code points whose contribution differs from the plain rule, ascending.</summary>",
        "        internal static readonly int[] CodePoints =",
        "        {",
    ]
    cps = sorted(table)
    for i in range(0, len(cps), 10):
        lines.append("            " + ", ".join("0x%04X" % c for c in cps[i:i + 10]) + ",")
    lines += [
        "        };",
        "",
        "        /// <summary>Each code point's contribution, in the order of <see cref=\"CodePoints\"/>.</summary>",
        "        internal static readonly string[] Parts =",
        "        {",
    ]
    for i in range(0, len(cps), 10):
        lines.append("            " + ", ".join('"%s"' % table[c] for c in cps[i:i + 10]) + ",")
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def main():
    a = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    a.add_argument("--dir", required=True, help="the folder holding %s" % UNICODE_DATA)
    a.add_argument("--check", action="store_true", help="compare with the committed table, write nothing")
    args = a.parse_args()

    maps, lower = parse(read_pinned(args.dir, UNICODE_DATA, UNICODE_DATA_SHA256))
    table = {}
    for cp in set(maps) | set(lower):
        got = contribution(cp, maps, lower)
        if got != plain(cp):
            table[cp] = got
    if unicodedata.unidata_version == VERSION:
        bad = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF
               and table.get(cp, plain(cp)) != python_contribution(cp)]
        if bad:
            sys.exit("%d code points differ from Python's NFKD, first U+%04X" % (len(bad), bad[0]))
        oracle = "every code point equal to Python's NFKD (Unicode %s)" % VERSION
    else:
        oracle = "NOT checked against Python's NFKD (Python's Unicode is %s)" % unicodedata.unidata_version
    source = render(table)
    summary = "Unicode %s, %d code points, %s" % (VERSION, len(table), oracle)

    if args.check:
        with open(OUT, encoding="utf-8", newline="") as f:
            same = f.read() == source
        print("%s: %s (%s)" % (os.path.basename(OUT), "matches" if same else "DIFFERS", summary))
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    print("wrote %s: %s" % (OUT, summary))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""The OnlyWorlds tools list -> Runtime/Core/OWTools.cs (OWTools.All), the rows OWOpeners.For reads.

The list (github.com/OnlyWorlds/tools, tools.json) is vendored byte for byte at codegen/tools/tools.json and
pinned in codegen/tools-pin.json (the commit and the file's sha256); the npm SDK and the Python package pin the
same commit. A tool listed after a release is offered from the next one, as the schema pin moves. Only the keys
OWOpeners.For reads are baked (id, name, url, client, rung, open); the rest of each row (the checks, the maker)
stays in the list.

    python codegen/generate_tools.py                 check the vendored file against the pin, write the C#
    python codegen/generate_tools.py --check         exit 1 if the vendored file or the C# is stale
    python codegen/generate_tools.py --repin COMMIT  vendor tools.json as GitHub serves it at COMMIT, pin it, write

The C# is written LF-only, as the repo's .gitattributes keeps it.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
VENDORED = ROOT / "codegen" / "tools" / "tools.json"
PIN = ROOT / "codegen" / "tools-pin.json"
OUT = ROOT / "Packages" / "com.onlyworlds.sdk" / "Runtime" / "Core" / "OWTools.cs"
REPO = "https://github.com/OnlyWorlds/tools"
KEYS = ("id", "name", "url", "client", "rung", "open")
OPEN_KEYS = ("world", "element", "needs")


def die(msg: str) -> None:
    raise SystemExit(f"tools: {msg}")


def text(value: Any, where: str) -> str:
    """A JSON string or null as a C# literal (JSON's escapes are C#'s for these characters)."""
    if value is None:
        return "null"
    if isinstance(value, str):
        return json.dumps(value)
    die(f"{where} is {value!r}; this generator bakes a string or null")
    return ""


def row(t: dict[str, Any]) -> str:
    rid = t.get("id")
    missing = [k for k in KEYS if k not in t]
    if missing:
        die(f"row {rid!r} has no {', '.join(missing)}")
    args = ", ".join(text(t[k], f"row {rid!r} {k}") for k in KEYS[:5])
    o = t["open"]
    if o is None:
        door = "null"
    elif isinstance(o, dict):
        door = "new OWToolOpen(" + ", ".join(text(o.get(k), f"row {rid!r} open.{k}") for k in OPEN_KEYS) + ")"
    else:
        die(f"row {rid!r} open is {o!r}; an object or null")
    return f"            new OWTool({args},\n                {door}),\n"


def render(data: bytes, pin: dict[str, Any]) -> str:
    doc = json.loads(data.decode("utf-8"))
    if doc.get("format") != 1:
        die(f"tools.json format {doc.get('format')!r}; this generator reads format 1")
    if not isinstance(doc.get("tools"), list):
        die("tools.json has no tools array")
    rows = "".join(row(t) for t in doc["tools"])
    return (
        "// <auto-generated>\n"
        f"// Generated by codegen/generate_tools.py from the OnlyWorlds tools list, {REPO} @ {pin['commit']}\n"
        f"// (tools.json sha256 {pin['sha256']}).\n"
        "// Do not edit by hand: the list is changed upstream, repinned (python codegen/generate_tools.py --repin <commit>)\n"
        "// and regenerated.\n"
        "// </auto-generated>\n"
        "\n"
        "using System;\n"
        "using System.Collections.Generic;\n"
        "\n"
        "namespace OnlyWorlds.Sdk\n"
        "{\n"
        "    /// <summary>\n"
        "    /// The OnlyWorlds tools list's rows (format 1), in the list's order, as of this release: the keys\n"
        "    /// <see cref=\"OWOpeners\"/> reads. A tool listed after a release is offered from the next one.\n"
        "    /// </summary>\n"
        "    public static class OWTools\n"
        "    {\n"
        "        /// <summary>The list's repository.</summary>\n"
        f"        public const string Repository = \"{REPO}\";\n"
        "\n"
        "        /// <summary>The commit of the list these rows came from.</summary>\n"
        f"        public const string Commit = \"{pin['commit']}\";\n"
        "\n"
        "        /// <summary>sha256 of tools.json at <see cref=\"Commit\"/>.</summary>\n"
        f"        public const string Sha256 = \"{pin['sha256']}\";\n"
        "\n"
        "        /// <summary>The rows, in the list's order.</summary>\n"
        "        public static readonly IReadOnlyList<OWTool> All = Array.AsReadOnly(new[]\n"
        "        {\n"
        f"{rows}"
        "        });\n"
        "    }\n"
        "}\n"
    )


def read_pinned() -> tuple[dict[str, Any], bytes]:
    pin: dict[str, Any] = json.loads(PIN.read_text(encoding="utf-8"))
    data = VENDORED.read_bytes()
    got = hashlib.sha256(data).hexdigest()
    if got != pin["sha256"]:
        die(f"codegen/tools/tools.json is sha256 {got}; the pin says {pin['sha256']}")
    return pin, data


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the vendored file or the C# is stale")
    mode.add_argument("--repin", metavar="COMMIT", help="vendor tools.json at COMMIT (40 hex), pin it, write")
    args = ap.parse_args()
    if args.repin is not None:
        if not re.fullmatch(r"[0-9a-f]{40}", args.repin):
            die("--repin takes the full 40-hex commit")
        url = f"https://raw.githubusercontent.com/OnlyWorlds/tools/{args.repin}/tools.json"
        with urllib.request.urlopen(url, timeout=30) as res:
            data = res.read()
        pin = {
            "_what": "The recorded pin for the vendored OnlyWorlds tools list (codegen/tools/tools.json, byte for byte"
            " as GitHub serves it at the commit). Do not edit by hand: python codegen/generate_tools.py --repin"
            " <commit>, and review the diff. Kept equal to the npm SDK's and the Python package's pins on purpose.",
            "repo": REPO,
            "commit": args.repin,
            "sha256": hashlib.sha256(data).hexdigest(),
            "pinned_at": datetime.date.today().isoformat(),
        }
        VENDORED.parent.mkdir(exist_ok=True)
        VENDORED.write_bytes(data)
        PIN.write_bytes((json.dumps(pin, indent=2) + "\n").encode("utf-8"))
        OUT.write_bytes(render(data, pin).encode("utf-8"))
        print(f"pinned {args.repin}, sha256 {pin['sha256']}; wrote {OUT.name}")
        return 0
    pin, data = read_pinned()
    want = render(data, pin)
    if args.check:
        have = OUT.read_bytes().decode("utf-8") if OUT.is_file() else ""
        if have != want:
            print(f"STALE: {OUT.name} does not match what the pinned tools list generates", file=sys.stderr)
            return 1
        print(f"ok: {OUT.name} matches the tools list at {pin['commit']}")
        return 0
    OUT.write_bytes(want.encode("utf-8"))  # bytes: LF on every platform
    print(f"wrote {OUT.name} from the tools list at {pin['commit']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

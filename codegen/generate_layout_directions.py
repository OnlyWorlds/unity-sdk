#!/usr/bin/env python3
"""The by-links-3d directions table -> Packages/com.onlyworlds.sdk/Runtime/Core/OWLayout.Directions.cs
(OWLayout.DirectionBits), the table OWLayout.LayoutByLinks3d reads.

by-links-3d packs a world's groups apart, each in its own direction: for K parts, row s of the table's list for K
(the layout page, profiles/layout.md, "The directions table"). The page says the table is read, never computed, every
digit parsed with correct rounding, a zero written -0.0 kept as written. It is read here from the pinned dist's own
copy (codegen/schema-dist/profiles/layout-by-links-3d.directions.json, whose sha256 the method's fixture names as
table_sha256; Python's json reads a decimal exactly) and written as bit patterns, so no parser of a decimal literal
stands between the table and the method. The vectors are flat, K = 1 first: the K vectors of K start at vector
K * (K - 1) / 2, so at double 3 * K * (K - 1) / 2. OWLayoutByLinks3dTests holds the table to the vendored copy, bit
for bit.

    python codegen/generate_layout_directions.py           write the C#
    python codegen/generate_layout_directions.py --check   exit 1 if the C# is stale

The C# is written LF-only, as the repo's .gitattributes keeps it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "codegen" / "schema-dist" / "profiles" / "layout-by-links-3d.directions.json"
OUT = ROOT / "Packages" / "com.onlyworlds.sdk" / "Runtime" / "Core" / "OWLayout.Directions.cs"


def flat_directions(doc: dict) -> tuple[int, list[float]]:
    k_max = doc["k_max"]
    table = doc["directions"]
    if not isinstance(k_max, int) or sorted(table, key=int) != [str(k) for k in range(1, k_max + 1)]:
        raise ValueError(f"the directions table holds K = 1 to k_max ({k_max}), each once")
    flat: list[float] = []
    for k in range(1, k_max + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"K = {k} does not hold {k} vectors")
        for p in row:
            if not isinstance(p, list) or len(p) != 3 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in p):
                raise ValueError(f"K = {k} holds a vector that is not [x, y, z]")
            flat += [float(p[0]), float(p[1]), float(p[2])]
    return k_max, flat


def bits(v: float) -> str:
    return "0x" + struct.pack(">d", v).hex().upper() + "UL"


def render() -> str:
    data = TABLE.read_bytes()
    k_max, flat = flat_directions(json.loads(data.decode("utf-8")))
    lines = [
        "// <auto-generated>",
        f"// Generated by codegen/generate_layout_directions.py from codegen/schema-dist/profiles/layout-by-links-3d.directions.json (sha256 {hashlib.sha256(data).hexdigest()}).",
        "// Do not edit by hand: the table moves with the pin, and this is regenerated.",
        "// </auto-generated>",
        "",
        "namespace OnlyWorlds.Sdk",
        "{",
        "    public static partial class OWLayout",
        "    {",
        "        /// <summary>The largest count of parts the directions table holds a row for.</summary>",
        f"        internal const int DirectionsMax = {k_max};",
        "",
        "        /// <summary>",
        "        /// The by-links-3d layout's directions: for each count of parts K from 1 to DirectionsMax, K unit vectors",
        "        /// (x, y, z), flat, K = 1 first; the vectors of K start at double 3 * K * (K - 1) / 2. Bit patterns of the",
        "        /// pinned table's numbers, never computed at run time.",
        "        /// </summary>",
        "        internal static readonly ulong[] DirectionBits =",
        "        {",
    ]
    for i in range(0, len(flat), 3):
        x, y, z = flat[i], flat[i + 1], flat[i + 2]
        lines.append(f"            {bits(x)}, {bits(y)}, {bits(z)}, // {x!r}, {y!r}, {z!r}")
    lines += [
        "        };",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the C# is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        have = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if have != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run python codegen/generate_layout_directions.py)", file=sys.stderr)
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} matches the directions table")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

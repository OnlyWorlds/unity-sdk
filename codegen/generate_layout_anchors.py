#!/usr/bin/env python3
"""The shared layout fixture's anchors -> Packages/com.onlyworlds.sdk/Runtime/Core/OWLayout.Anchors.cs (OWLayout.Anchors),
the table OWLayout.LayoutByKind reads.

LayoutByKind starts each kind of element at a point on a circle and pulls it back there. The method is chaotic: one
anchor one unit in the last place off moves a large world's picture by a tenth of its frame. Cosine and sine are not
correctly rounded and differ between runtimes, so the anchors are never computed at run time: they are one table of
253 points (for k kinds, k = 1 to 22, the k points, flat, the points of k from index k * (k - 1)), the same float64
values the TypeScript SDK and the Python package hold. They are read here from the vendored copy of the shared fixture
(Tests/Editor/Fixtures/layout/by-kind.json, its `anchors`; Python's json reads a decimal exactly) and written as bit
patterns, so no parser of a decimal literal stands between the fixture and the table. Each type's colour group (its
place in colors.order), which orders the kinds, comes from the pinned dist's presentation.json, as the TypeScript
SDK's ELEMENT_GROUPS and GROUP_ORDER do; the test holds both to the fixture's `groups` and `group_order`.

    python codegen/generate_layout_anchors.py           write the C#
    python codegen/generate_layout_anchors.py --check   exit 1 if the C# is stale

The C# is written LF-only, as the repo's .gitattributes keeps it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "Packages" / "com.onlyworlds.sdk"
FIXTURE = PACKAGE / "Tests" / "Editor" / "Fixtures" / "layout" / "by-kind.json"
OUT = PACKAGE / "Runtime" / "Core" / "OWLayout.Anchors.cs"
PRESENTATION = ROOT / "codegen" / "schema-dist" / "presentation.json"
KINDS = 22


def flat_anchors(table: dict) -> list[float]:
    if sorted(table, key=int) != [str(k) for k in range(1, KINDS + 1)]:
        raise ValueError(f"the anchor table holds k = 1 to {KINDS}, each once")
    flat: list[float] = []
    for k in range(1, KINDS + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"k = {k} does not hold {k} points")
        for p in row:
            if not isinstance(p, list) or len(p) != 2 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in p):
                raise ValueError(f"k = {k} holds a point that is not [x, y]")
            flat += [float(p[0]), float(p[1])]
    return flat


def bits(v: float) -> str:
    return "0x" + struct.pack(">d", v).hex().upper() + "UL"


def render() -> str:
    data = FIXTURE.read_bytes()
    flat = flat_anchors(json.loads(data.decode("utf-8"))["anchors"])
    lines = [
        "// <auto-generated>",
        f"// Generated by codegen/generate_layout_anchors.py from Tests/Editor/Fixtures/layout/by-kind.json (sha256 {hashlib.sha256(data).hexdigest()}), its anchors.",
        "// Do not edit by hand: the fixture moves, and this is regenerated.",
        "// </auto-generated>",
        "",
        "namespace OnlyWorlds.Sdk",
        "{",
        "    public static partial class OWLayout",
        "    {",
        "        /// <summary>",
        "        /// The by-kind layout's anchors: for each count of kinds k from 1 to 22, the k points (x, y) on the unit circle",
        "        /// where the kinds sit, flat, k = 1 first; the points of k start at index k * (k - 1). Bit patterns of the",
        "        /// shared fixture's numbers, never computed at run time, so the picture is the same in every runtime.",
        "        /// </summary>",
        "        internal static readonly ulong[] AnchorBits =",
        "        {",
    ]
    for i in range(0, len(flat), 2):
        x, y = flat[i], flat[i + 1]
        lines.append(f"            {bits(x)}, {bits(y)}, // {x!r}, {y!r}")
    pres_bytes = PRESENTATION.read_bytes()
    pres = json.loads(pres_bytes.decode("utf-8"))
    order = pres["colors"]["order"]
    types = pres["types"]
    if len(types) != KINDS:
        raise ValueError(f"presentation.json lists {len(types)} types, not {KINDS}")
    lines += [
        "        };",
        "",
        "        /// <summary>",
        f"        /// Each element type's colour group as its place in <c>colors.order</c> ({', '.join(order)}), from the pinned",
        f"        /// presentation.json (sha256 {hashlib.sha256(pres_bytes).hexdigest()}): the first-party drawing defaults the",
        "        /// kinds are ordered by, never a caller's override. Also the 22 types the layout reads, by slug.",
        "        /// </summary>",
        "        internal static readonly System.Collections.Generic.Dictionary<string, int> GroupRank =",
        "            new System.Collections.Generic.Dictionary<string, int>(System.StringComparer.Ordinal)",
        "            {",
    ]
    for slug in sorted(types):
        family = types[slug]["family"]
        if family not in order:
            raise ValueError(f"presentation.json gives {slug} the family {family!r}, not one of colors.order")
        lines.append(f'                ["{slug}"] = {order.index(family)}, // {family}')
    lines += [
        "            };",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the C# is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        have = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if have != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run python codegen/generate_layout_anchors.py)", file=sys.stderr)
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} matches the fixture's anchors")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
